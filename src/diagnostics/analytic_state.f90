module tiago_analytic_state
    !! Shifted-circle tokamak state with |B| = B0 R0 / R, an analytic oracle for
    !! the profile diagnostics. Labels (rho, theta, phi):
    !!     R = R0 + Delta (1 - rho^2) + a rho cos(theta),   Z = a rho sin(theta).
    !! Parameters p = (R0, a, Delta, B0). The pointwise map and its derivatives
    !! are generated by FortSym (gen/gen_profile_kernels.f90).
    use, intrinsic :: iso_fortran_env, only: dp => real64
    use tiago_real_space_state, only: real_space_state_t
    use tiago_circular_state, only: circular_state
    implicit none
    private

    real(dp), parameter :: pi = acos(-1.0_dp)

    type, extends(real_space_state_t), public :: circular_state_t
        real(dp) :: r0 = 3.0_dp, a = 1.0_dp, delta = 0.0_dp, b0 = 2.5_dp
    contains
        procedure :: n_params => circ_n_params
        procedure :: get_params => circ_get_params
        procedure :: set_params => circ_set_params
        procedure :: eval => circ_eval
        procedure :: param_jvp => circ_param_jvp
        procedure :: param_vjp => circ_param_vjp
        procedure :: initial_guess => circ_initial_guess
    end type circular_state_t

contains

    pure integer function circ_n_params(self)
        class(circular_state_t), intent(in) :: self
        circ_n_params = 4
    end function circ_n_params

    pure subroutine circ_get_params(self, p)
        class(circular_state_t), intent(in) :: self
        real(dp), intent(out) :: p(:)
        p(1:4) = [self%r0, self%a, self%delta, self%b0]
    end subroutine circ_get_params

    subroutine circ_set_params(self, p)
        class(circular_state_t), intent(inout) :: self
        real(dp), intent(in) :: p(:)
        self%r0 = p(1)
        self%a = p(2)
        self%delta = p(3)
        self%b0 = p(4)
    end subroutine circ_set_params

    pure subroutine circ_eval(self, u, x, dxdu, b, dbdu)
        class(circular_state_t), intent(in) :: self
        real(dp), intent(in) :: u(3)
        real(dp), intent(out) :: x(3), dxdu(3, 3), b, dbdu(3)
        real(dp) :: dxdp(3, 4), dbdp(4)

        call circular_state(u(1), u(2), u(3), self%r0, self%a, self%delta, self%b0, &
            x, dxdu, dxdp, b, dbdu, dbdp)
    end subroutine circ_eval

    pure subroutine circ_param_jvp(self, u, dp_, dx, db)
        class(circular_state_t), intent(in) :: self
        real(dp), intent(in) :: u(3), dp_(:)
        real(dp), intent(out) :: dx(3), db
        real(dp) :: x(3), dxdu(3, 3), dxdp(3, 4), b, dbdu(3), dbdp(4)

        call circular_state(u(1), u(2), u(3), self%r0, self%a, self%delta, self%b0, &
            x, dxdu, dxdp, b, dbdu, dbdp)
        dx = matmul(dxdp, dp_(1:4))
        db = dot_product(dbdp, dp_(1:4))
    end subroutine circ_param_jvp

    pure subroutine circ_param_vjp(self, u, xbar, bbar, pbar)
        class(circular_state_t), intent(in) :: self
        real(dp), intent(in) :: u(3), xbar(3), bbar
        real(dp), intent(inout) :: pbar(:)
        real(dp) :: x(3), dxdu(3, 3), dxdp(3, 4), b, dbdu(3), dbdp(4)

        call circular_state(u(1), u(2), u(3), self%r0, self%a, self%delta, self%b0, &
            x, dxdu, dxdp, b, dbdu, dbdp)
        pbar(1:4) = pbar(1:4) + matmul(xbar, dxdp) + bbar * dbdp
    end subroutine circ_param_vjp

    pure subroutine circ_initial_guess(self, x, u)
        !! Exact for Delta = 0; a good start otherwise.
        class(circular_state_t), intent(in) :: self
        real(dp), intent(in) :: x(3)
        real(dp), intent(out) :: u(3)
        real(dp) :: r, rc

        r = hypot(x(1), x(2))
        rc = self%r0 + 0.5_dp * self%delta
        u(1) = max(hypot(r - rc, x(3)) / self%a, 1.0e-3_dp)
        u(2) = atan2(x(3), r - rc)
        u(3) = atan2(x(2), x(1))
    end subroutine circ_initial_guess
end module tiago_analytic_state
